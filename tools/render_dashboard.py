#!/usr/bin/env python3
"""Render a static, offline HTML dashboard from signal-capture evidence.

Reads docs/evidence/signal-captures/*.json (written by capture_signals.py)
and emits a single self-contained HTML file — no server, no build step, no
framework, no network fetch. Open it directly in a browser. This is the
"validation" axis of the observability dashboard split (the other two —
Decision Journey, and live Jaeger — are separate, higher-cost pieces; this one
is free because it only reads files already on disk).

Usage:
    python -m tools.render_dashboard [--in DIR] [--out FILE]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).parent.parent


def load_captures(in_dir: Path) -> list[dict]:
    captures = []
    for fpath in sorted(in_dir.glob("*.json")):
        if fpath.name == "summary.json":
            continue
        captures.append(json.loads(fpath.read_text()))
    return captures


def render(captures: list[dict]) -> str:
    n_detected = sum(1 for c in captures if c["detected"])
    n_fp = sum(1 for c in captures if c["false_positive_ticks"])
    n_total = len(captures)
    gate_pass = n_detected == n_total and n_fp == 0
    gate_status = "good" if gate_pass else ("critical" if n_detected == 0 else "warning")
    gate_label = "READY" if gate_pass else "NOT READY"

    payload = json.dumps(captures)

    cards = "\n".join(_scenario_card(i, c) for i, c in enumerate(captures))

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>PatchTST Signal Validation — Go/No-Go</title>
<style>
{_CSS}
</style>
</head>
<body>
<div class="viz-root">
  <header class="page-header">
    <div>
      <h1>PatchTST Signal Validation</h1>
      <p class="muted">Offline capture — {n_total} scenario(s), no cluster, no cloud spend</p>
    </div>
    <button id="theme-toggle" class="theme-toggle" aria-label="Toggle dark mode">◐</button>
  </header>

  <section class="gate-tile status-{gate_status}">
    <div class="gate-icon">{"✓" if gate_pass else "✕"}</div>
    <div>
      <div class="gate-hero">{n_detected} / {n_total}</div>
      <div class="gate-label">{gate_label} — deploy gate {"cleared" if gate_pass else "NOT cleared"}</div>
    </div>
  </section>

  <section class="cards">
{cards}
  </section>

  <footer class="muted">Generated by tools/render_dashboard.py from docs/evidence/signal-captures/</footer>
</div>

<script type="application/json" id="capture-data">{payload}</script>
<script>
{_JS}
</script>
</body>
</html>
"""


def _scenario_card(idx: int, c: dict) -> str:
    status = "good" if (c["detected"] and not c["false_positive_ticks"]) else (
        "warning" if c["detected"] else "critical"
    )
    badge = "DETECTED" if c["detected"] else "MISSED"
    icon = "✓" if c["detected"] else "✕"
    latency = c["detection_latency_ticks"] if c["detection_latency_ticks"] is not None else "—"
    fp = len(c["false_positive_ticks"])
    return f"""    <article class="card">
      <div class="card-head">
        <h2>{c["scenario"]}</h2>
        <p class="muted">{c["description"]}</p>
      </div>
      <div class="badge-row">
        <span class="badge status-{status}"><span aria-hidden="true">{icon}</span> {badge}</span>
        <div class="stat"><span class="stat-label">Latency</span><span class="stat-value">{latency}<span class="stat-unit"> ticks</span></span></div>
        <div class="stat"><span class="stat-label">False positives</span><span class="stat-value">{fp}</span></div>
        <div class="stat"><span class="stat-label">Runtime</span><span class="stat-value">{c["elapsed_s"]}<span class="stat-unit"> s</span></span></div>
      </div>
      <div class="chart-wrap" data-scenario-index="{idx}">
        <svg class="chart-svg" data-scenario-index="{idx}" role="img" aria-label="Score over ticks for {c["scenario"]}"></svg>
        <div class="tooltip" hidden></div>
      </div>
      <button class="table-toggle" data-scenario-index="{idx}" aria-expanded="false">Show table view</button>
      <div class="table-wrap" data-scenario-index="{idx}" hidden></div>
    </article>"""


