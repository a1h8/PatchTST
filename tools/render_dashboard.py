_JS = r"""
(function () {
  const root = document.documentElement;
  const toggle = document.getElementById("theme-toggle");
  const saved = localStorage.getItem("dv-theme");
  if (saved) root.setAttribute("data-theme", saved);
  toggle.addEventListener("click", function () {
    const next = root.getAttribute("data-theme") === "dark" ? "light" : "dark";
    root.setAttribute("data-theme", next);
    localStorage.setItem("dv-theme", next);
  });

  const captures = JSON.parse(document.getElementById("capture-data").textContent);
  const SEVERITY_VAR = {
    normal: "--status-good",
    warning: "--status-warning",
    critical: "--status-critical",
  };

  const vizRoot = document.querySelector(".viz-root");
  function cssVar(name) {
    return getComputedStyle(vizRoot).getPropertyValue(name).trim();
  }

  function renderChart(svg, capture) {
    const timeline = capture.timeline;
    const w = 640, h = 220, padL = 36, padR = 12, padT = 12, padB = 24;
    const plotW = w - padL - padR, plotH = h - padT - padB;

    const ticks = timeline.map(function (e) { return e.tick; });
    const scores = timeline.map(function (e) { return e.score; });
    const maxScore = Math.max.apply(null, scores.concat([3.0])) * 1.15;
    const minTick = Math.min.apply(null, ticks), maxTick = Math.max.apply(null, ticks);

    function x(tick) { return padL + (maxTick === minTick ? 0 : (tick - minTick) / (maxTick - minTick) * plotW); }
    function y(score) { return padT + plotH - (score / maxScore) * plotH; }

    svg.setAttribute("viewBox", "0 0 " + w + " " + h);
    svg.innerHTML = "";

    function el(tag, attrs) {
      const e = document.createElementNS("http://www.w3.org/2000/svg", tag);
      for (const k in attrs) e.setAttribute(k, attrs[k]);
      return e;
    }

    // gridlines (y: 0, 1.8 warning, 3.0 critical) — skip a label that would
    // collide with the previous one (min 10px vertical gap) rather than
    // overlapping text; the gridline itself is still drawn.
    let lastLabelY = -Infinity;
    [0, 1.8, 3.0].forEach(function (val) {
      if (val > maxScore) return;
      const gy = y(val);
      svg.appendChild(el("line", { x1: padL, x2: w - padR, y1: gy, y2: gy, class: val === 0 ? "baseline" : "ref-line" }));
      if (Math.abs(gy - lastLabelY) >= 10) {
        const label = el("text", { x: 4, y: gy + 3, class: "axis-label" });
        label.textContent = val.toFixed(1);
        svg.appendChild(label);
        lastLabelY = gy;
      }
    });

    // incident_at reference (ground truth)
    const ix = x(capture.incident_at);
    svg.appendChild(el("line", { x1: ix, x2: ix, y1: padT, y2: h - padB, class: "ref-line" }));
    const ilabel = el("text", { x: ix + 4, y: padT + 10, class: "ref-label" });
    ilabel.textContent = "incident onset";
    svg.appendChild(ilabel);

    // detected marker
    if (capture.first_incident_tick != null) {
      const dx = x(capture.first_incident_tick);
      const dlabel = el("text", { x: dx + 4, y: padT + 22, class: "ref-label" });
      dlabel.textContent = "→ INCIDENT";
      svg.appendChild(dlabel);
    }

    // score line
    const pathD = timeline.map(function (e, i) {
      return (i === 0 ? "M" : "L") + x(e.tick).toFixed(1) + "," + y(e.score).toFixed(1);
    }).join(" ");
    svg.appendChild(el("path", { d: pathD, class: "score-line" }));

    // severity-colored dots
    timeline.forEach(function (e) {
      const color = cssVar(SEVERITY_VAR[e.severity] || "--status-good");
      svg.appendChild(el("circle", {
        cx: x(e.tick), cy: y(e.score), r: 4.5, fill: color, class: "score-dot",
        "data-tick": e.tick,
      }));
    });

    // x-axis ticks (first, mid, last)
    [ticks[0], ticks[Math.floor(ticks.length / 2)], ticks[ticks.length - 1]].forEach(function (t) {
      const label = el("text", { x: x(t), y: h - 6, class: "axis-label", "text-anchor": "middle" });
      label.textContent = t;
      svg.appendChild(label);
    });

    return { x: x, y: y, padT: padT, plotH: plotH };
  }

  function attachCrosshair(wrap, svg, capture, scales) {
    const tooltip = wrap.querySelector(".tooltip");
    const timeline = capture.timeline;

    function nearest(clientTick) {
      let best = timeline[0], bestDist = Infinity;
      timeline.forEach(function (e) {
        const d = Math.abs(e.tick - clientTick);
        if (d < bestDist) { bestDist = d; best = e; }
      });
      return best;
    }

    svg.addEventListener("pointermove", function (evt) {
      const rect = svg.getBoundingClientRect();
      const px = (evt.clientX - rect.left) / rect.width * 640;
      const minTick = timeline[0].tick, maxTick = timeline[timeline.length - 1].tick;
      const padL = 36, padR = 12, plotW = 640 - padL - padR;
      const clientTick = minTick + (px - padL) / plotW * (maxTick - minTick);
      const entry = nearest(clientTick);
      const sx = scales.x(entry.tick), sy = scales.y(entry.score);

      tooltip.hidden = false;
      tooltip.style.left = (sx / 640 * rect.width) + "px";
      tooltip.style.top = (sy / 220 * rect.height) + "px";
      tooltip.innerHTML =
        '<div class="tt-row"><span>tick</span><span class="tt-value">' + entry.tick + '</span></div>' +
        '<div class="tt-row"><span>score</span><span class="tt-value">' + entry.score + '</span></div>' +
        '<div class="tt-row"><span>severity</span><span class="tt-value">' + entry.severity + '</span></div>' +
        '<div class="tt-row"><span>regime</span><span class="tt-value">' + (entry.regime || "—") + '</span></div>';
    });
    svg.addEventListener("pointerleave", function () { tooltip.hidden = true; });
  }

  document.querySelectorAll(".chart-svg").forEach(function (svg) {
    const idx = svg.getAttribute("data-scenario-index");
    const capture = captures[idx];
    const scales = renderChart(svg, capture);
    const wrap = svg.closest(".chart-wrap");
    attachCrosshair(wrap, svg, capture, scales);
  });

  document.querySelectorAll(".table-toggle").forEach(function (btn) {
    btn.addEventListener("click", function () {
      const idx = btn.getAttribute("data-scenario-index");
      const capture = captures[idx];
      const target = document.querySelector('.table-wrap[data-scenario-index="' + idx + '"]');
      const expanded = btn.getAttribute("aria-expanded") === "true";
      if (!expanded && !target.dataset.built) {
        const rows = capture.timeline.map(function (e) {
          return "<tr><td>" + e.tick + "</td><td>" + e.severity + "</td><td>" + e.score +
            "</td><td>" + (e.regime || "—") + "</td><td>" + (e.mode || "—") + "</td><td>" + e.method + "</td></tr>";
        }).join("");
        target.innerHTML =
          "<table><thead><tr><th>Tick</th><th>Severity</th><th>Score</th><th>Regime</th><th>Mode</th><th>Method</th></tr></thead>" +
          "<tbody>" + rows + "</tbody></table>";
        target.dataset.built = "1";
      }
      target.hidden = expanded;
      btn.setAttribute("aria-expanded", String(!expanded));
      btn.textContent = expanded ? "Show table view" : "Hide table view";
    });
  });
})();
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--in", dest="in_dir", default=str(ROOT / "docs/evidence/signal-captures"))
    parser.add_argument("--out", default=str(ROOT / "docs/evidence/signal-captures/dashboard.html"))
    args = parser.parse_args(argv)

    in_dir = Path(args.in_dir)
    captures = load_captures(in_dir)
    if not captures:
        print(f"no capture JSON files found in {in_dir}")
        return 1

    html = render(captures)
    out_path = Path(args.out)
    out_path.write_text(html)
    print(f"wrote {out_path} ({len(captures)} scenario(s))")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
